import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const source = fs.readFileSync(path.join(root, 'src/content/teacher-authored-context.ts'), 'utf8');
const advanced = fs.readFileSync(path.join(root, 'src/content/advanced.ts'), 'utf8');
const ids = [...advanced.matchAll(/makeLesson\("([^"]+)"/g)].map(m => m[1]);
const contextIds = [...source.matchAll(/^  "([^"]+)": \{/gm)].map(m => m[1]);
const missing = ids.filter(id => !contextIds.includes(id));
const dup = contextIds.filter((id,i)=>contextIds.indexOf(id)!==i);
const bad = ['lorem ipsum','placeholder text','random structure','use this word'];
const hits = bad.filter(x=>source.toLowerCase().includes(x));
const readingCount = (source.match(/\n    reading: /g)||[]).length;
const readingUzCount = (source.match(/\n    readingUz: /g)||[]).length;
const listeningCount = (source.match(/\n    listening: \[\[/g)||[]).length;
const speakingCount = (source.match(/\n    speaking: /g)||[]).length;
const writingCount = (source.match(/\n    writing: /g)||[]).length;
console.log(`advanced lessons: ${ids.length}`);
console.log(`contexts: ${contextIds.length}`);
console.log(`reading EN/UZ: ${readingCount}/${readingUzCount}`);
console.log(`listening dialogues: ${listeningCount}`);
console.log(`speaking/writing: ${speakingCount}/${writingCount}`);
console.log(`missing: ${missing.length ? missing.join(', ') : 'none'}`);
console.log(`duplicates: ${dup.length ? dup.join(', ') : 'none'}`);
console.log(`template markers: ${hits.length ? hits.join(', ') : 'none'}`);
if (ids.length!==54 || contextIds.length!==54 || readingCount!==54 || readingUzCount!==54 || listeningCount!==54 || speakingCount!==54 || writingCount!==54 || missing.length || dup.length || hits.length) process.exitCode=1;
